// Generates shared/botSandbox.ts from scripts/bot-sandbox.js: the HTML of the bot sandbox (used as
// the srcdoc of an <iframe sandbox="allow-scripts">) and the sha256 of its inline script.
// The script is allowed by hash because a sandboxed document has an opaque origin, so a CSP 'self'
// source would not match anything. The hub adds the same hash to the page CSP it serves (srcdoc
// frames inherit their parent's policy).
//   node scripts/sandbox-csp.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function buildSandbox() {
  const js = readFileSync(path.join(root, 'scripts', 'bot-sandbox.js'), 'utf8').replace(/\r\n/g, '\n').trim();
  const hash = 'sha256-' + createHash('sha256').update(js, 'utf8').digest('base64');
  const page = (connect) =>
    `<!doctype html><html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src '${hash}'; worker-src blob:; connect-src ${connect}"><script>${js}</script></head><body></body></html>`;
  const ts = `// GENERATED by scripts/sandbox-csp.mjs from scripts/bot-sandbox.js. Do not edit by hand.
/* eslint-disable */
/** CSP source for the bot sandbox's inline script. */
export const SANDBOX_SCRIPT_HASH = ${JSON.stringify(hash)};
/** srcdoc for a bot without network access. */
export const SANDBOX_HTML = ${JSON.stringify(page("'none'"))};
/** srcdoc for a bot its owner allowed to use the internet (https only). */
export const SANDBOX_NET_HTML = ${JSON.stringify(page('https:'))};
`;
  return { hash, ts };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { hash, ts } = buildSandbox();
  writeFileSync(path.join(root, 'shared', 'botSandbox.ts'), ts);
  console.log('shared/botSandbox.ts written, script ' + hash);
}
